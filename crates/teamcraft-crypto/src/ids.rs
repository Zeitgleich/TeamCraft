//! Minimal ID newtypes used inside signed and encrypted structures.
//!
//! TODO(proto): switch to the shared ID types from `teamcraft-proto` once this crate may depend on
//! it (and move `ClientMessageId` there as a wire type). These are Snowflake IDs (`u64`), matching the server's primary keys; the binary encoding
//! (big-endian `u64`) is part of every signature and must stay stable when switching.

use std::fmt;

use rand_core::CryptoRngCore;
use tls_codec::{TlsDeserializeBytes, TlsSerialize, TlsSize};

macro_rules! snowflake_id {
  ($(#[$meta:meta])* $name:ident) => {
    $(#[$meta])*
    #[derive(
      Clone, Copy, Debug, PartialEq, Eq, PartialOrd, Ord, Hash, TlsSerialize, TlsDeserializeBytes, TlsSize,
    )]
    pub struct $name(u64);

    impl $name {
      pub const fn new(value: u64) -> Self {
        Self(value)
      }

      pub const fn get(self) -> u64 {
        self.0
      }
    }

    impl fmt::Display for $name {
      fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        write!(f, "{}", self.0)
      }
    }
  };
}

snowflake_id!(
  /// A user account.
  UserId
);
snowflake_id!(
  /// One device (client installation) of a user. Globally unique, not per user.
  DeviceId
);
snowflake_id!(
  /// A conversation: channel, group DM or DM. One MLS group per conversation.
  ConversationId
);

/// Random 128-bit message ID generated by the sending client before encryption and bound into the
/// AEAD (e2ee.md §4.4). Separate from the server's Snowflake message ID, which only orders messages.
#[derive(Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Hash, TlsSerialize, TlsDeserializeBytes, TlsSize)]
pub struct ClientMessageId([u8; 16]);

impl ClientMessageId {
  pub fn generate(rng: &mut impl CryptoRngCore) -> Self {
    let mut bytes = [0u8; 16];
    rng.fill_bytes(&mut bytes);
    Self(bytes)
  }

  pub const fn from_bytes(bytes: [u8; 16]) -> Self {
    Self(bytes)
  }

  pub const fn as_bytes(&self) -> &[u8; 16] {
    &self.0
  }
}

impl fmt::Debug for ClientMessageId {
  fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
    f.write_str("ClientMessageId(")?;
    for byte in self.0 {
      write!(f, "{byte:02x}")?;
    }
    f.write_str(")")
  }
}
