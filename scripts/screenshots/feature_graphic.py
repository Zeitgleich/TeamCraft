#!/usr/bin/env python3
"""Writes the Google Play feature graphic (1024 x 500, no alpha) for every store language.

The brand's style of the GitHub social preview: a dark navy gradient, the full mark with the
wordmark, and the tagline. The SVG source per language is written next to the PNG
(apps/android/store/<locale>/images/featureGraphic.svg), so it can be checked and re-rendered.

Needs python3 with Pillow, Inkscape 1.x and the Inter font installed. Run from the repository root:
python3 scripts/screenshots/feature_graphic.py
"""

import re
import subprocess
import tempfile
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parents[2]
BRAND = ROOT / "assets/brand"
STORE = ROOT / "apps/android/store"

WIDTH = 1024
HEIGHT = 500
# The mark and the wordmark side by side, centred; heights in px.
MARK_SIZE = 150
WORDMARK_HEIGHT = 96
GAP = 30
ROW_CENTER_Y = 190

TEXTS = {
  "en-US": (
    "Self-hosted team chat, end-to-end encrypted",
    "Channels · Calls · Meetings · Desktop, web and mobile",
  ),
  "de-DE": (
    "Team-Chat zum Selbsthosten, Ende-zu-Ende-verschlüsselt",
    "Channels · Anrufe · Meetings · Desktop, Web und Mobil",
  ),
}


def main() -> None:
  for locale, (tagline, features) in TEXTS.items():
    folder = STORE / locale / "images"
    folder.mkdir(parents=True, exist_ok=True)
    source = folder / "featureGraphic.svg"
    source.write_text(feature_graphic(tagline, features))
    render(source, folder / "featureGraphic.png")
    print((folder / "featureGraphic.png").relative_to(ROOT))


def feature_graphic(tagline: str, features: str) -> str:
  mark_box, mark_body = inner(BRAND / "mark.svg")
  word_box, word_body = inner(BRAND / "wordmark-dark.svg")
  word_width = WORDMARK_HEIGHT * word_box[2] / word_box[3]
  row_x = (WIDTH - (MARK_SIZE + GAP + word_width)) / 2
  return f"""<svg xmlns="http://www.w3.org/2000/svg" width="{WIDTH}" height="{HEIGHT}" viewBox="0 0 {WIDTH} {HEIGHT}">
  <!-- Generated by scripts/screenshots/feature_graphic.py from assets/brand. -->
  <defs>
    <radialGradient id="glow" gradientUnits="userSpaceOnUse" cx="512" cy="170" r="620">
      <stop offset="0" stop-color="#0b2a66"/>
      <stop offset="0.55" stop-color="#081736"/>
      <stop offset="1" stop-color="#050b19"/>
    </radialGradient>
  </defs>
  <rect width="{WIDTH}" height="{HEIGHT}" fill="url(#glow)"/>
  <svg x="{row_x:.1f}" y="{ROW_CENTER_Y - MARK_SIZE / 2:.1f}" width="{MARK_SIZE}" height="{MARK_SIZE}" viewBox="{' '.join(map(fmt, mark_box))}">
{mark_body}
  </svg>
  <svg x="{row_x + MARK_SIZE + GAP:.1f}" y="{ROW_CENTER_Y - WORDMARK_HEIGHT / 2:.1f}" width="{word_width:.1f}" height="{WORDMARK_HEIGHT}" viewBox="{' '.join(map(fmt, word_box))}">
{word_body}
  </svg>
  <g font-family="Inter" text-anchor="middle">
    <text x="512" y="348" font-size="32" font-weight="600" fill="#f2f5fa">{tagline}</text>
    <text x="512" y="402" font-size="22" font-weight="400" fill="#9fb0cc">{features}</text>
  </g>
</svg>
"""


def inner(path: Path) -> tuple[tuple[float, ...], str]:
  """The viewBox and the content of an SVG file (without its outer element)."""
  svg = path.read_text()
  box = tuple(float(v) for v in re.search(r'viewBox="([^"]+)"', svg).group(1).split())
  start = svg.index(">", svg.index("<svg")) + 1
  return box, svg[start:svg.rindex("</svg>")].strip("\n")


def render(source: Path, out: Path) -> None:
  """Inkscape renders the SVG; the PNG loses its alpha channel, as Play requires."""
  with tempfile.TemporaryDirectory() as tmp:
    raster = Path(tmp) / "raster.png"
    subprocess.run(
      ["inkscape", str(source), "--export-type=png", f"--export-filename={raster}",
       f"--export-width={WIDTH}", f"--export-height={HEIGHT}"],
      check=True, capture_output=True,
    )
    Image.open(raster).convert("RGB").save(out, optimize=True)


def fmt(value: float) -> str:
  return f"{value:g}"


if __name__ == "__main__":
  main()
