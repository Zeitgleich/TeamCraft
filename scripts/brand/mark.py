#!/usr/bin/env python3
"""Writes the TeamCraft mark (assets/brand/mark.svg) from its construction.

The mark is built from exact geometry, not traced: three heads (circles), three bodies and the
speech bubble. Every outline is a closed chain of straight lines and circular arcs, with tangent
fillets of a given radius between neighbouring elements, so all curves are true arcs and every
joint is smooth. The values were measured from the supplied artwork
(assets/brand/reference/mark.png) and snapped to the 30° grid the drawing follows.

Coordinates are those of the 1254 px reference image. Run from the repository root:
python3 scripts/brand/mark.py
"""

import math
from dataclasses import dataclass
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "assets/brand/mark.svg"

# The square the mark sits in (reference image coordinates), centred on the drawing.
VIEW = (62.0, 77.0, 1130.0)
# Clear space between a head and the bodies around it.
HEAD_GAP = 15.0
HEAD_TOP = (626.5, 260.0, 144.5)
HEAD_LEFT = (202.3, 621.5, 131.5)
HEAD_RIGHT = (1051.3, 621.5, 131.5)
DOTS = ((528.0, 755.5), (625.8, 755.5), (723.7, 755.5))
DOT_RADIUS = 36.1
# The dark upper face of the left body ends at this line (y = SPLIT_SLOPE * x + SPLIT_OFFSET).
SPLIT_SLOPE = 0.607
SPLIT_OFFSET = 716.1

COLORS = {
  "head_top": ("#005af5", "#0079fd"),
  "head_left": ("#02aeac", "#0cd5c0"),
  "head_right": ("#1490fb", "#2cb7fd"),
  "body_top": ("#004bd3", "#005ce6"),
  "body_right": ("#047efc", "#27b0fd"),
  "body_left_shade": "#03a0a4",
  "body_left": "#1de7d5",
  "dots": "#0063ee",
}


@dataclass(frozen=True)
class Line:
  """A straight edge through `point`, walked along `angle` (degrees, y down)."""

  point: tuple[float, float]
  angle: float


@dataclass(frozen=True)
class Arc:
  """An edge on a circle. `convex`: the shape lies inside the circle (walked clockwise)."""

  center: tuple[float, float]
  radius: float
  convex: bool


@dataclass(frozen=True)
class Corner:
  """The joint after an element: a fillet of `radius` (0 = sharp) near `hint`."""

  radius: float
  hint: tuple[float, float]


def main() -> None:
  OUT.write_text(svg())


def svg(with_dots: bool = True) -> str:
  """The whole mark as an SVG document (without its dots for the animated loading screen)."""
  x, y, size = VIEW
  return f"""<svg xmlns="http://www.w3.org/2000/svg" viewBox="{fmt(x)} {fmt(y)} {fmt(size)} {fmt(size)}">
  <!-- Generated by scripts/brand/mark.py; edit the construction there. -->
  <defs>
{defs()}
  </defs>
{shapes(with_dots=with_dots)}
</svg>
"""


def defs(prefix: str = "") -> str:
  """Gradients and clip paths the shapes refer to; `prefix` keeps ids unique when embedded."""
  shade_clip = (
    f"M150 {fmt(SPLIT_SLOPE * 150 + SPLIT_OFFSET)}L700 {fmt(SPLIT_SLOPE * 700 + SPLIT_OFFSET)}"
    "L700 450L150 450Z"
  )
  return "\n".join([
    gradient(f"{prefix}head-top", "head_top", (500, 390), (760, 130)),
    gradient(f"{prefix}head-left", "head_left", (110, 720), (300, 520)),
    gradient(f"{prefix}head-right", "head_right", (955, 720), (1145, 520)),
    gradient(f"{prefix}body-top", "body_top", (300, 480), (910, 700)),
    gradient(f"{prefix}body-right", "body_right", (660, 1150), (1000, 760)),
    f'    <clipPath id="{prefix}body-left-shade"><path d="{shade_clip}"/></clipPath>',
  ])


def shapes(prefix: str = "", with_dots: bool = True) -> str:
  """The drawing itself, in reference image coordinates."""
  left = outline(body_left())
  maybe_dots = dots(f'fill="{COLORS["dots"]}"') if with_dots else ""
  return f"""  <path fill="url(#{prefix}body-right)" d="{outline(body_right())}"/>
  <path fill="url(#{prefix}body-top)" d="{outline(body_top())}"/>
  <path fill="{COLORS["body_left"]}" d="{left}"/>
  <path fill="{COLORS["body_left_shade"]}" clip-path="url(#{prefix}body-left-shade)" d="{left}"/>
  {circle(HEAD_TOP, f'fill="url(#{prefix}head-top)"')}
  {circle(HEAD_LEFT, f'fill="url(#{prefix}head-left)"')}
  {circle(HEAD_RIGHT, f'fill="url(#{prefix}head-right)"')}
  <path fill="#fff" d="{outline(bubble())}"/>
  {maybe_dots}"""


def silhouette_paths() -> list[str]:
  """The people (bodies and heads) as plain path data, for one-colour versions."""
  return [outline(body_right()), outline(body_top()), outline(body_left())] + [
    circle_path(head) for head in (HEAD_TOP, HEAD_LEFT, HEAD_RIGHT)
  ]


def dots(attributes: str, radius: float = DOT_RADIUS) -> str:
  return f"<g {attributes}>{''.join(circle((x, y, radius)) for x, y in DOTS)}</g>"


def body_top() -> list:
  """The top person's shoulders: a band from the upper left down to the right of the bubble."""
  return [
    Line((374.1, 403.2), -30), Corner(56, (459, 352)),
    clear_of(HEAD_TOP, 30), Corner(65, (911, 607)),
    clear_of(HEAD_RIGHT, 90), Corner(54, (905, 843)),
    # Just inside the bubble's lower right corner, so it disappears under the bubble there.
    Line((850.5, 876.5), 150), Corner(0, (820, 895)),
    Line((780, 880), -135), Corner(0, (590, 690)),
    clear_of(HEAD_LEFT, -150), Corner(62, (243, 482)),
  ]


def body_right() -> list:
  """The right person's body: top right shoulder, around the right head, down to the bottom."""
  top_gap = gap(HEAD_TOP)
  right_gap = gap(HEAD_RIGHT)
  return [
    clear_of(HEAD_TOP, -30), Corner(62, (782, 349)),
    Line((908.1, 420.6), 30), Corner(54, (956, 448)),
    Line((955.8, 484.9), 90), Corner(65, (956, 520)),
    right_gap, Corner(100, (960, 745)),
    Line((994.6, 756), 22), Corner(80, (1071, 801)),
    Line((1071.7, 881.1), 90), Corner(90, (1071, 983)),
    Line((908.6, 1078.9), 150), Corner(90, (637, 1236)),
    Line((637.5, 1045.6), -90), Corner(0, (637.5, 700)),
    # Under the band from here on.
    Line((637.5, 700), -105), Corner(0, (540, 400)),
    # Tangent to the clear space: it leaves the arc without a corner.
    top_gap, Corner(0, (680, 410)),
  ]


def body_left() -> list:
  """The left person's body: the left side, the shoulder around the left head, the bottom."""
  return [
    Line((183.2, 891.7), -90), Corner(84, (183, 801)),
    gap(HEAD_LEFT), Corner(0, (333, 690)),
    shoulder_left(), Corner(0, (600, 829)),
    # Under the bubble and its tail; it comes out at the tail's left edge.
    Line((600, 829), 90), Corner(0, (600, 900)),
    Line((600, 900), 0), Corner(0, (630, 900)),
    Line((630, 900), 90), Corner(0, (630, 1000)),
    Line((630, 1000), 180), Corner(0, (616.5, 1000)),
    Line((616.5, 1000), 90), Corner(90, (616.5, 1231)),
    Line((346.2, 1079.4), -150), Corner(90, (183, 983)),
  ]


def shoulder_left() -> Arc:
  """The rounded top of the left shoulder, touching the clear space around the left head."""
  radius = 149.8
  hx, hy, hr = HEAD_LEFT
  dx, dy = 466.7 - hx, 760.2 - hy
  # Centred so the two circles touch (a hair of overlap keeps the intersection defined).
  scale = (hr + HEAD_GAP + radius - 0.01) / math.hypot(dx, dy)
  return Arc((hx + dx * scale, hy + dy * scale), radius, True)


def bubble() -> list:
  """The speech bubble: a rounded rectangle with the tail at the bottom left of its centre."""
  tail_angle = math.degrees(math.atan2(941 - 1007, 713 - 635))
  return [
    Line((413, 593.5), 0), Corner(83, (840.5, 593.5)),
    Line((840.5, 593.5), 90), Corner(76, (840.5, 915.5)),
    Line((840.5, 915.5), 180), Corner(48, (743, 915.5)),
    Line((713, 941), tail_angle + 180), Corner(12, (616.5, 1022)),
    Line((616.5, 941), -90), Corner(13, (616.5, 915.5)),
    Line((413, 915.5), 180), Corner(80, (413, 915.5)),
    Line((413, 915.5), -90), Corner(85, (413, 593.5)),
  ]


def clear_of(head: tuple[float, float, float], angle: float) -> Line:
  """An edge walked along `angle` that just keeps the clear space around `head`."""
  x, y, r = head
  nx, ny = inward(Line((0, 0), angle))
  return Line((x + nx * (r + HEAD_GAP), y + ny * (r + HEAD_GAP)), angle)


def gap(head: tuple[float, float, float]) -> Arc:
  """The edge of the clear space around a head: the body lies outside it."""
  x, y, r = head
  return Arc((x, y), r + HEAD_GAP, False)


def outline(chain: list) -> str:
  """The SVG path of a closed chain `[element, corner, element, corner, ...]`."""
  elements = chain[0::2]
  corners = chain[1::2]
  count = len(elements)
  joints = [joint(elements[i], elements[(i + 1) % count], corners[i]) for i in range(count)]
  path = []
  for i in range(count):
    entry = joints[i - 1]["to"]
    leave = joints[i]
    if i == 0:
      path.append(f"M{fmt(entry[0])} {fmt(entry[1])}")
    path.append(segment(elements[i], entry, leave["from"]))
    if leave["radius"] > 0:
      sweep = 1 if leave["convex"] else 0
      r = fmt(leave["radius"])
      path.append(f"A{r} {r} 0 0 {sweep} {fmt(leave['to'][0])} {fmt(leave['to'][1])}")
  return "".join(path) + "Z"


def joint(first, second, corner: Corner) -> dict:
  """Where `first` hands over to `second`: the two tangent points of the fillet (or one point)."""
  sharp = closest(intersections(first, second, 0, 0), corner.hint)
  is_convex = cross(tangent(first, sharp), tangent(second, sharp)) > 0
  if corner.radius == 0:
    return {"from": sharp, "to": sharp, "radius": 0, "convex": is_convex}
  side = 1 if is_convex else -1
  center = closest(intersections(first, second, side * corner.radius, side * corner.radius), sharp)
  return {
    "from": foot(first, center),
    "to": foot(second, center),
    "radius": corner.radius,
    "convex": is_convex,
  }


def segment(element, start, end) -> str:
  """The path command that walks `element` from `start` to `end`."""
  if isinstance(element, Line):
    return f"L{fmt(end[0])} {fmt(end[1])}"
  cx, cy = element.center
  a0 = math.atan2(start[1] - cy, start[0] - cx)
  a1 = math.atan2(end[1] - cy, end[0] - cx)
  sweep_angle = (a1 - a0) % (2 * math.pi) if element.convex else (a0 - a1) % (2 * math.pi)
  large = 1 if sweep_angle > math.pi else 0
  sweep = 1 if element.convex else 0
  r = fmt(element.radius)
  return f"A{r} {r} 0 {large} {sweep} {fmt(end[0])} {fmt(end[1])}"


def intersections(first, second, offset_first: float, offset_second: float) -> list:
  """Points where both elements meet after moving each `offset` into the shape."""
  a = shifted(first, offset_first)
  b = shifted(second, offset_second)
  if isinstance(a, Line) and isinstance(b, Line):
    return line_line(a, b)
  if isinstance(a, Line):
    return line_circle(a, b)
  if isinstance(b, Line):
    return line_circle(b, a)
  return circle_circle(a, b)


def shifted(element, offset: float):
  """`element` moved `offset` towards the inside of the shape (negative: outwards)."""
  if isinstance(element, Line):
    nx, ny = inward(element)
    return Line((element.point[0] + nx * offset, element.point[1] + ny * offset), element.angle)
  radius = element.radius - offset if element.convex else element.radius + offset
  return Arc(element.center, radius, element.convex)


def inward(line: Line) -> tuple[float, float]:
  """The unit normal of a line pointing into the shape (outlines run clockwise on screen)."""
  dx, dy = direction(line)
  return (-dy, dx)


def tangent(element, point) -> tuple[float, float]:
  """The walking direction of `element` at `point`."""
  if isinstance(element, Line):
    return direction(element)
  rx = point[0] - element.center[0]
  ry = point[1] - element.center[1]
  length = math.hypot(rx, ry)
  sign = 1 if element.convex else -1
  return (-ry / length * sign, rx / length * sign)


def foot(element, point) -> tuple[float, float]:
  """The point of `element` closest to `point`."""
  if isinstance(element, Line):
    dx, dy = direction(element)
    t = (point[0] - element.point[0]) * dx + (point[1] - element.point[1]) * dy
    return (element.point[0] + dx * t, element.point[1] + dy * t)
  rx = point[0] - element.center[0]
  ry = point[1] - element.center[1]
  length = math.hypot(rx, ry)
  return (
    element.center[0] + rx / length * element.radius,
    element.center[1] + ry / length * element.radius,
  )


def line_line(a: Line, b: Line) -> list:
  adx, ady = direction(a)
  bdx, bdy = direction(b)
  det = cross((adx, ady), (bdx, bdy))
  if abs(det) < 1e-9:
    return []
  t = cross((b.point[0] - a.point[0], b.point[1] - a.point[1]), (bdx, bdy)) / det
  return [(a.point[0] + adx * t, a.point[1] + ady * t)]


def line_circle(line: Line, arc: Arc) -> list:
  dx, dy = direction(line)
  fx = line.point[0] - arc.center[0]
  fy = line.point[1] - arc.center[1]
  b = fx * dx + fy * dy
  c = fx * fx + fy * fy - arc.radius**2
  disc = b * b - c
  # A line that just touches the circle (an edge tangent to a head's clear space) meets it once.
  if disc < -1e-6:
    return []
  disc = max(disc, 0)
  root = math.sqrt(disc)
  return [(line.point[0] + dx * t, line.point[1] + dy * t) for t in (-b - root, -b + root)]


def circle_circle(a: Arc, b: Arc) -> list:
  dx = b.center[0] - a.center[0]
  dy = b.center[1] - a.center[1]
  d = math.hypot(dx, dy)
  if d == 0 or d > a.radius + b.radius or d < abs(a.radius - b.radius):
    return []
  along = (a.radius**2 - b.radius**2 + d * d) / (2 * d)
  h = math.sqrt(max(a.radius**2 - along**2, 0))
  mx = a.center[0] + dx * along / d
  my = a.center[1] + dy * along / d
  return [(mx + h * dy / d, my - h * dx / d), (mx - h * dy / d, my + h * dx / d)]


def closest(points: list, hint) -> tuple[float, float]:
  if not points:
    raise ValueError(f"elements don't meet near {hint}")
  return min(points, key=lambda p: math.hypot(p[0] - hint[0], p[1] - hint[1]))


def direction(line: Line) -> tuple[float, float]:
  angle = math.radians(line.angle)
  return (math.cos(angle), math.sin(angle))


def cross(a, b) -> float:
  return a[0] * b[1] - a[1] * b[0]


def gradient(id_: str, key: str, start, end) -> str:
  first, last = COLORS[key]
  return (
    f'    <linearGradient id="{id_}" gradientUnits="userSpaceOnUse" x1="{start[0]}" y1="{start[1]}" '
    f'x2="{end[0]}" y2="{end[1]}">\n'
    f'      <stop offset="0" stop-color="{first}"/><stop offset="1" stop-color="{last}"/>\n'
    "    </linearGradient>"
  )


def circle(spec, attributes: str = "") -> str:
  x, y, r = spec
  extra = f" {attributes}" if attributes else ""
  return f'<circle{extra} cx="{fmt(x)}" cy="{fmt(y)}" r="{fmt(r)}"/>'


def circle_path(spec) -> str:
  """A circle as path data (two half arcs), for formats without a circle element."""
  x, y, r = spec
  return (
    f"M{fmt(x - r)} {fmt(y)}A{fmt(r)} {fmt(r)} 0 1 0 {fmt(x + r)} {fmt(y)}"
    f"A{fmt(r)} {fmt(r)} 0 1 0 {fmt(x - r)} {fmt(y)}Z"
  )


def fmt(value: float) -> str:
  text = f"{value:.2f}".rstrip("0").rstrip(".")
  return "0" if text == "-0" else text


if __name__ == "__main__":
  main()
