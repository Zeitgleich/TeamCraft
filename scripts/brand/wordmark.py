#!/usr/bin/env python3
"""Writes the TeamCraft wordmark (assets/brand/wordmark.svg and wordmark-dark.svg).

The letters come from the supplied artwork (assets/brand/reference/wordmark.png, reduced to a
48-colour palette to keep it small); the typeface is not available as a font file. Each colour is traced at four times the size, its outlines are
smoothed along the curve (which removes the pixel steps of the artwork) and then fitted with as
few cubic Béziers as keep within 0.12 px of it.

Needs numpy, scipy, Pillow and potrace. Run from the repository root:
python3 scripts/brand/wordmark.py
"""

import json
import subprocess
import tempfile
from pathlib import Path

import numpy as np
from PIL import Image
from scipy import ndimage

ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / "assets/brand/reference/wordmark.png"
OUT_DIR = ROOT / "assets/brand"

UPSCALE = 4
# Smoothing along the outline, in upscaled pixels.
SMOOTHING = 10.0
TOLERANCE = 0.12
VIEW_BOX = "125 190 1914 330"
# "Team" and "Craft" on light and on dark backgrounds.
COLORS = {
  "wordmark.svg": ("#0b1c3a", "#005dfc"),
  "wordmark-dark.svg": ("#f2f5fa", "#5c9dff"),
}


def main() -> None:
  image = np.asarray(Image.open(SOURCE).convert("RGBA")).astype(float)
  alpha = image[..., 3] / 255
  blueness = np.clip((image[..., 2] - 120) / 80, 0, 1)
  paths = [trace(alpha * (1 - blueness)), trace(alpha * blueness)]
  for name, (team, craft) in COLORS.items():
    (OUT_DIR / name).write_text(
      f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="{VIEW_BOX}">\n'
      "  <!-- Generated by scripts/brand/wordmark.py. -->\n"
      f'  <path fill="{team}" d="{paths[0]}"/>\n'
      f'  <path fill="{craft}" d="{paths[1]}"/>\n'
      "</svg>\n"
    )


def trace(coverage: np.ndarray) -> str:
  """The outline of one colour (coverage 0..1 per pixel) as SVG path data."""
  height, width = coverage.shape
  big = Image.fromarray((coverage * 255).astype(np.uint8)).resize(
    (width * UPSCALE, height * UPSCALE), Image.LANCZOS
  )
  mask = ndimage.gaussian_filter(np.asarray(big).astype(float), UPSCALE * 0.7) > 127
  rings = []
  for ring in polygon_rings(mask):
    rings.append(smooth_ring(ring, SMOOTHING) / UPSCALE)
  return "".join(ring_path(ring) for ring in rings)


def polygon_rings(mask: np.ndarray) -> list[np.ndarray]:
  """The outlines of `mask` as closed polygons (potrace without curve fitting)."""
  with tempfile.TemporaryDirectory() as tmp:
    bitmap = Path(tmp) / "mask.pbm"
    geojson = Path(tmp) / "mask.json"
    Image.fromarray(((~mask) * 255).astype(np.uint8)).save(bitmap)
    subprocess.run(
      ["potrace", "-b", "geojson", "-a", "0", "-t", "400", "-o", str(geojson), str(bitmap)],
      check=True,
    )
    features = json.loads(geojson.read_text())["features"]
  height = mask.shape[0]
  rings = []
  for feature in features:
    for ring in feature["geometry"]["coordinates"]:
      points = np.array(ring[:-1], float)
      points[:, 1] = height - points[:, 1]
      rings.append(points)
  return rings


def smooth_ring(points: np.ndarray, sigma: float) -> np.ndarray:
  """`points` resampled every unit along the closed outline and smoothed along it."""
  closed = np.vstack([points, points[:1]])
  steps = np.hypot(*np.diff(closed, axis=0).T)
  along = np.r_[0, np.cumsum(steps)]
  samples = np.linspace(0, along[-1], int(along[-1]), endpoint=False)
  x = np.interp(samples, along, closed[:, 0])
  y = np.interp(samples, along, closed[:, 1])
  return np.c_[
    ndimage.gaussian_filter1d(x, sigma, mode="wrap"),
    ndimage.gaussian_filter1d(y, sigma, mode="wrap"),
  ]


def ring_path(ring: np.ndarray) -> str:
  """A closed outline as `M … C … Z`, split in two halves that are fitted separately."""
  half = len(ring) // 2
  curves = []
  for chain in (ring[: half + 1], np.vstack([ring[half:], ring[:1]])):
    start = unit(chain[1] - chain[0])
    end = unit(chain[-2] - chain[-1])
    curves += fit(chain, start, end)
  parts = [f"M{num(curves[0][0][0])} {num(curves[0][0][1])}"]
  for curve in curves:
    parts.append("C" + " ".join(f"{num(curve[k][0])} {num(curve[k][1])}" for k in (1, 2, 3)))
  return "".join(parts) + "Z"


def fit(points: np.ndarray, start: np.ndarray, end: np.ndarray) -> list[np.ndarray]:
  """Cubic Béziers through `points` with the given end tangents (Schneider's algorithm)."""
  params = chord_lengths(points)
  curve = least_squares(points, start, end, params)
  for _ in range(4):
    params = newton_step(curve, points, params)
    curve = least_squares(points, start, end, params)
  errors = np.hypot(*(bezier(curve, params) - points).T)
  worst = int(errors.argmax())
  if errors[worst] <= TOLERANCE or len(points) < 8:
    return [curve]
  worst = min(max(worst, 3), len(points) - 4)
  middle = unit(points[worst + 1] - points[worst - 1])
  return fit(points[: worst + 1], start, -middle) + fit(points[worst:], middle, end)


def least_squares(points, start, end, params) -> np.ndarray:
  """The Bézier from the first to the last point whose handles fit `points` best."""
  first, last = points[0], points[-1]
  a1 = np.outer(3 * (1 - params) ** 2 * params, start)
  a2 = np.outer(3 * (1 - params) * params**2, end)
  matrix = np.array([[np.sum(a1 * a1), np.sum(a1 * a2)], [np.sum(a1 * a2), np.sum(a2 * a2)]])
  rest = points - bezier(np.array([first, first, last, last]), params)
  rhs = np.array([np.sum(a1 * rest), np.sum(a2 * rest)])
  span = np.hypot(*(last - first))
  try:
    alpha1, alpha2 = np.linalg.solve(matrix, rhs)
  except np.linalg.LinAlgError:
    alpha1 = alpha2 = span / 3
  if not (span * 1e-3 < alpha1 < span * 2 and span * 1e-3 < alpha2 < span * 2):
    alpha1 = alpha2 = span / 3
  return np.array([first, first + alpha1 * start, last + alpha2 * end, last])


def newton_step(curve, points, params) -> np.ndarray:
  """Better curve parameters for `points` (one Newton-Raphson step towards the closest point)."""
  t = params[:, None]
  position = bezier(curve, params)
  d1 = 3 * ((1 - t) ** 2 * (curve[1] - curve[0]) + 2 * (1 - t) * t * (curve[2] - curve[1])
            + t**2 * (curve[3] - curve[2]))
  d2 = 6 * ((1 - t) * (curve[2] - 2 * curve[1] + curve[0]) + t * (curve[3] - 2 * curve[2] + curve[1]))
  numerator = np.sum((position - points) * d1, axis=1)
  denominator = np.sum(d1 * d1, axis=1) + np.sum((position - points) * d2, axis=1)
  safe = np.where(np.abs(denominator) > 1e-9, denominator, 1)
  step = np.where(np.abs(denominator) > 1e-9, numerator / safe, 0)
  return np.clip(params - step, 0, 1)


def bezier(curve: np.ndarray, params: np.ndarray) -> np.ndarray:
  t = params[:, None]
  return ((1 - t) ** 3 * curve[0] + 3 * (1 - t) ** 2 * t * curve[1]
          + 3 * (1 - t) * t**2 * curve[2] + t**3 * curve[3])


def chord_lengths(points: np.ndarray) -> np.ndarray:
  along = np.r_[0, np.cumsum(np.hypot(*np.diff(points, axis=0).T))]
  return along / along[-1]


def unit(vector: np.ndarray) -> np.ndarray:
  return vector / np.hypot(*vector)


def num(value: float) -> str:
  return f"{value:.2f}".rstrip("0").rstrip(".")


if __name__ == "__main__":
  main()
