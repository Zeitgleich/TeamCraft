#!/usr/bin/env python3
"""Writes the background of the macOS dmg window (apps/desktop/packaging/macos/), at 1x and 2x.

The window shows the app on the left and the Applications folder on the right with an arrow from
one to the other; the positions are the ones apps/desktop/tauri.conf.json (`bundle.macOS.dmg`) and
make-dmg.sh give the icons. The backdrop is a mid-tone slate, because Finder draws the icon labels
black in Light Mode and white in Dark Mode and both must stay readable (about 4.5:1 each). No text:
the window would need it in every language.

Needs python3 and either rsvg-convert or ImageMagick 7 built with librsvg (`magick`), like
icons.py. Run from the repository root: python3 scripts/brand/dmg_background.py
"""

import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

import icons  # noqa: E402
import mark  # noqa: E402

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "apps/desktop/packaging/macos"

# Window content in points; keep in sync with tauri.conf.json and make-dmg.sh.
WIDTH = 660
HEIGHT = 400
APP_POSITION = (180, 190)
APPLICATIONS_POSITION = (480, 190)
# Finder's icon size in the window (make-dmg.sh); the arrow keeps clear of the icons.
ICON_SIZE = 128
# Top and bottom of the backdrop: relative luminance about 0.18, between black and white labels.
BACKDROP = ("#738298", "#66758b")
ARROW = "#ffffff"
MARK_WIDTH = 56
MARK_TOP = 34


def main() -> None:
  svg = background()
  for scale, name in ((1, "dmg-background.png"), (2, "dmg-background@2x.png")):
    out = OUT / name
    out.write_bytes(png(svg, WIDTH * scale, HEIGHT * scale))
    print(out.relative_to(ROOT))


def background() -> str:
  scale = MARK_WIDTH / (icons.MARK_BOX[2] - icons.MARK_BOX[0])
  mark_height = (icons.MARK_BOX[3] - icons.MARK_BOX[1]) * scale
  return f"""<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {WIDTH} {HEIGHT}">
  <!-- Generated by scripts/brand/dmg_background.py from the mark (scripts/brand/mark.py). -->
  <defs>
    <linearGradient id="backdrop" x1="0" y1="0" x2="0" y2="1">
      <stop offset="0" stop-color="{BACKDROP[0]}"/><stop offset="1" stop-color="{BACKDROP[1]}"/>
    </linearGradient>
{mark.defs("m-")}
  </defs>
  <rect width="{WIDTH}" height="{HEIGHT}" fill="url(#backdrop)"/>
{icons.place_mark(mark.shapes("m-"), scale, WIDTH / 2, MARK_TOP + mark_height / 2)}
{arrow()}
</svg>
"""


def arrow() -> str:
  """A rounded arrow between the two icons, at the height of their centres."""
  y = APP_POSITION[1]
  start = APP_POSITION[0] + ICON_SIZE / 2 + 28
  end = APPLICATIONS_POSITION[0] - ICON_SIZE / 2 - 28
  head = 16
  return (
    f'  <g fill="none" stroke="{ARROW}" stroke-width="6" stroke-linecap="round" '
    f'stroke-linejoin="round" opacity="0.9">\n'
    f'    <path d="M{start} {y} H{end}"/>\n'
    f'    <path d="M{end - head} {y - head} L{end} {y} L{end - head} {y + head}"/>\n'
    "  </g>"
  )


def png(svg: str, width: int, height: int) -> bytes:
  with tempfile.TemporaryDirectory() as tmp:
    source = Path(tmp) / "in.svg"
    raster = Path(tmp) / "raster.png"
    target = Path(tmp) / "out.png"
    source.write_text(svg)
    if shutil.which("rsvg-convert"):
      subprocess.run(["rsvg-convert", "-w", str(width), "-h", str(height), "-o", str(raster),
                      str(source)], check=True)
    else:
      density = 96 * width / WIDTH
      subprocess.run(["magick", "-background", "none", "-density", f"{density:.4f}", str(source),
                      "-resize", f"{width}x{height}!", str(raster)], check=True)
    # Opaque, no timestamps: a re-run without changes leaves the files byte for byte as they are.
    subprocess.run(["magick", str(raster), "-background", BACKDROP[1], "-alpha", "remove",
                    "-alpha", "off", "-strip", "-define", "png:exclude-chunks=date,time", "-define", "png:compression-level=9",
                    f"PNG24:{target}"], check=True)
    return target.read_bytes()


if __name__ == "__main__":
  main()
