import Foundation

/// The core's JSON view models as they arrive over the bridge (`ChatAnswer` of teamcraft-client-api,
/// the server's meeting responses). Plain data: every decision about what it means stays in the core.
/// Only the fields the app shows are declared; unknown fields are ignored. Keys are snake_case on
/// the wire, ids are decimal strings.
enum Wire {
  static func decode<T: Decodable>(_ type: T.Type, from json: String) -> T? {
    let decoder = JSONDecoder()
    decoder.keyDecodingStrategy = .convertFromSnakeCase
    return try? decoder.decode(type, from: Data(json.utf8))
  }
}

/// Where a file stands: `remote`, `uploading`, `downloading`, `local`, `failed`, or for an own file
/// that stopped going up `upload_stalled` (retried on "Try again") and `upload_failed` (for good).
struct FileTransfer: Decodable, Equatable, Sendable {
  let state: String
  let doneBytes: Int64?
  let totalBytes: Int64?
  /// Failed attempts of an upload that is retried by itself.
  let failedAttempts: Int?
  /// Where the decrypted file is, once `local`.
  let path: String?
  let reason: String?

  var isInProgress: Bool { state == "uploading" || state == "downloading" }

  /// An own file still on its way up, or stopped: it can be cancelled.
  var isCancellable: Bool { state == "uploading" || state == "upload_stalled" }

  /// 0...1 while uploading or downloading.
  var maybeProgress: Double? {
    guard isInProgress, let total = totalBytes, total > 0 else { return nil }
    return min(1, Double(doneBytes ?? 0) / Double(total))
  }
}

struct FileInfo: Decodable, Equatable, Identifiable, Sendable {
  let conversation: String
  let message: String
  let fileId: String
  let fileName: String
  let mediaType: String
  let sizeBytes: Int64
  /// PNG bytes of the thumbnail the sender's core made (images and videos).
  let maybeThumbnailPng: [UInt8]?
  let transfer: FileTransfer

  var id: String { fileId }
  var isImage: Bool { mediaType.hasPrefix("image/") }
  var maybeThumbnailData: Data? { maybeThumbnailPng.map { Data($0) } }
}

/// A link preview generated by the sender's core (the receiving device never fetches the URL).
struct LinkPreview: Decodable, Equatable, Sendable {
  let url: String
  let maybeTitle: String?
  let maybeDescription: String?
  let maybeSiteName: String?
  let maybeImage: [UInt8]?

  var maybeImageData: Data? { maybeImage.map { Data($0) } }

  /// Only web links are opened from a preview; the URL comes from another user's message.
  var maybeOpenableURL: URL? {
    guard let url = URL(string: url), let scheme = url.scheme?.lowercased(), scheme == "http" || scheme == "https"
    else { return nil }
    return url
  }
}

/// What a message has beyond its text (`MessageExtras`).
struct MessageExtras: Decodable, Equatable, Sendable {
  let message: String
  let files: [FileInfo]?
  let maybeLinkPreview: LinkPreview?
  /// The server rejected this own message; it waits for "retry" or "delete".
  let isSendFailed: Bool?
  let maybeReply: ReplyPreview?
  let isPinned: Bool?
  let isSaved: Bool?
  /// Earlier versions, oldest first (empty if never edited).
  let edits: [MessageEdit]?
}

/// The quoted message of a reply, as much as the reader can see of it.
struct ReplyPreview: Decodable, Equatable, Sendable {
  let author: String
  let excerpt: String
}

/// An earlier version of an edited message.
struct MessageEdit: Decodable, Equatable, Sendable {
  let body: String
  /// Unix milliseconds.
  let replacedAt: Int64
}

/// Where a message link points (`teamcraft:/c/…/m/…[/t/…]`).
struct PermalinkTarget: Decodable, Equatable, Sendable {
  let conversation: String
  let message: String
  let maybeThread: String?
}

/// The tagged answer of a `ChatQuery`; read the field that belongs to its `answer`.
struct ChatAnswer: Decodable, Sendable {
  let answer: String
  let extras: [MessageExtras]?
  let files: [FileInfo]?
  let maybeBytes: Int64?
  let maybeTarget: PermalinkTarget?
  let users: [String]?
  let maybeLink: String?
  let channels: [BrowsableChannel]?
}

/// The people part of the core's chat snapshot: who can be mentioned, and the former accounts that
/// only name their old messages.
struct PeopleSnapshot: Decodable, Sendable {
  struct Person: Decodable, Sendable {
    let id: String
    let username: String
    let displayName: String
    /// Deleted (issue #630): a tombstone the app names by its own "Deleted user" (issue #751).
    let isDeleted: Bool?

    /// The name to show: the app's own "Deleted user" for a deleted account, as on desktop and web.
    var shownName: String { isDeleted == true ? deletedUserName : displayName }
  }

  let me: Person
  /// The people to offer in lists, pickers and mentions.
  let users: [Person]?
  /// Deactivated and deleted accounts: offered nowhere, they only name their old messages.
  let formerUsers: [Person]?

  /// Names by user ID for reply quotes and calls: everyone this device knows, former accounts
  /// included.
  var namesById: [String: String] {
    let everyone = (users ?? []) + [me] + (formerUsers ?? [])
    return Dictionary(everyone.map { ($0.id, $0.shownName) }, uniquingKeysWith: { first, _ in first })
  }
}

/// The app's own name for a deleted account in the user's language, instead of the server's
/// placeholder (issue #751).
private var deletedUserName: String { String(localized: "user_deleted_name") }

extension MessageItem {
  /// The message with `deletedUserName` as its author's name when the author's account was deleted.
  func namingDeletedAuthor() -> MessageItem {
    guard isAuthorDeleted else { return self }
    var named = self
    named.authorName = deletedUserName
    return named
  }
}

extension SearchHitItem {
  /// The hit with `deletedUserName` as its author's name when the author's account was deleted.
  func namingDeletedAuthor() -> SearchHitItem {
    var named = self
    named.message = message.namingDeletedAuthor()
    return named
  }
}

/// A meeting as the server lists it (`GET /meetings`).
struct Meeting: Decodable, Equatable, Identifiable, Sendable {
  let id: String
  let title: String
  /// Unix milliseconds.
  let startsAt: Int64
  let endsAt: Int64
  /// `scheduled`, `cancelled` or `ended`.
  let status: String
  let conversationId: String
  let attendees: [MeetingAttendee]?

  var startDate: Date { Date(timeIntervalSince1970: TimeInterval(startsAt) / 1000) }
  var endDate: Date { Date(timeIntervalSince1970: TimeInterval(endsAt) / 1000) }

  /// The user's own answer to the invitation, if they are an invitee.
  func rsvp(of userId: String) -> RsvpAnswer? {
    attendees?.first { $0.userId == userId }.map { RsvpAnswer(rawValue: $0.rsvp) ?? .needsAction }
  }
}

struct MeetingAttendee: Decodable, Equatable, Sendable {
  let userId: String?
  let rsvp: String
}

struct MeetingList: Decodable, Sendable {
  let meetings: [Meeting]
}

/// An invitee's answer (`RsvpStatus` of the server).
enum RsvpAnswer: String, CaseIterable, Identifiable, Sendable {
  case needsAction = "needs_action"
  case accepted
  case declined
  case tentative

  var id: String { rawValue }
}
