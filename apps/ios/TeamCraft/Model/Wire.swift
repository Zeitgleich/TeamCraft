import Foundation

/// The core's JSON view models as they arrive over the bridge (`ChatAnswer` of teamcraft-client-api,
/// the server's meeting responses). Plain data: every decision about what it means stays in the core.
/// Only the fields the app shows are declared; unknown fields are ignored. Keys are snake_case on
/// the wire, ids are decimal strings.
enum Wire {
  static func decode<T: Decodable>(_ type: T.Type, from json: String) -> T? {
    let decoder = JSONDecoder()
    decoder.keyDecodingStrategy = .convertFromSnakeCase
    return try? decoder.decode(type, from: Data(json.utf8))
  }
}

/// Where a file stands: `remote`, `uploading`, `downloading`, `local`, `failed`, or for an own file
/// that stopped going up `upload_stalled` (retried on "Try again") and `upload_failed` (for good).
struct FileTransfer: Decodable, Equatable, Sendable {
  let state: String
  let doneBytes: Int64?
  let totalBytes: Int64?
  /// Failed attempts of an upload that is retried by itself.
  let failedAttempts: Int?
  /// Where the decrypted file is, once `local`.
  let path: String?
  let reason: String?

  var isInProgress: Bool { state == "uploading" || state == "downloading" }

  /// An own file still on its way up, or stopped: it can be cancelled.
  var isCancellable: Bool { state == "uploading" || state == "upload_stalled" }

  /// An upload whose attempts failed so far and that the core retries by itself (#742).
  var isRetrying: Bool { state == "uploading" && (doneBytes ?? 0) == 0 && (failedAttempts ?? 0) > 0 }

  /// It stopped because the file storage (or the server) is down, not this device's network.
  var isStorageUnavailable: Bool { reason == "storage_unavailable" }

  /// 0...1 while uploading or downloading.
  var maybeProgress: Double? {
    guard isInProgress, let total = totalBytes, total > 0 else { return nil }
    return min(1, Double(doneBytes ?? 0) / Double(total))
  }
}

struct FileInfo: Decodable, Equatable, Identifiable, Sendable {
  let conversation: String
  let message: String
  let fileId: String
  let fileName: String
  let mediaType: String
  let sizeBytes: Int64
  /// PNG bytes of the thumbnail the sender's core made (images and videos).
  let maybeThumbnailPng: [UInt8]?
  let transfer: FileTransfer
  /// Who wrote the message and when (Unix milliseconds), for the image viewer: the original author
  /// and time of an imported message (e2ee.md §4.10).
  var maybeSender: String?
  var maybeSentAt: Int64?
  /// Who wrote an imported message when that is nobody with an account here.
  var importedAuthor: ImportedAuthor?
  /// How long a video or voice message plays, from the sender.
  var maybeDurationMs: Int64?
  /// A voice message's waveform from the sender (#204), one loudness byte per bar; checked by the
  /// core, so present only on voice messages.
  var maybeWaveform: [UInt8]?

  var id: String { fileId }
  var isImage: Bool { mediaType.hasPrefix("image/") }
  var isVideo: Bool { mediaType.hasPrefix("video/") }
  /// A video that opens in the player: on the server or here, not one still going up.
  var opensInVideoPlayer: Bool { isVideo && ["local", "remote", "downloading", "failed"].contains(transfer.state) }
  var maybeThumbnailData: Data? { maybeThumbnailPng.map { Data($0) } }
  /// An audio file with a waveform: shown as a voice message with its own player (#204).
  var isVoiceMessage: Bool { mediaType.hasPrefix("audio/") && !(maybeWaveform ?? []).isEmpty }
}

/// Who wrote an imported message: `person` (the file's sender), `deleted` or `named` (a bot).
struct ImportedAuthor: Decodable, Equatable, Sendable {
  let kind: String
  let name: String?

  /// The name shown instead of an account: a bot's old name or "Deleted user"; nil for a person.
  var standInName: String? {
    switch kind {
    case "named": return name
    case "deleted": return deletedUserName
    default: return nil
    }
  }
}

/// A link preview generated by the sender's core (the receiving device never fetches the URL).
struct LinkPreview: Decodable, Equatable, Sendable {
  let url: String
  let maybeTitle: String?
  let maybeDescription: String?
  let maybeSiteName: String?
  let maybeImage: [UInt8]?

  var maybeImageData: Data? { maybeImage.map { Data($0) } }

  /// Only web links are opened from a preview; the URL comes from another user's message.
  var maybeOpenableURL: URL? {
    guard let url = URL(string: url), let scheme = url.scheme?.lowercased(), scheme == "http" || scheme == "https"
    else { return nil }
    return url
  }
}

/// What a message has beyond its text (`MessageExtras`).
struct MessageExtras: Decodable, Equatable, Sendable {
  let message: String
  let files: [FileInfo]?
  let maybeLinkPreview: LinkPreview?
  /// The server rejected this own message; it waits for "retry" or "delete".
  let isSendFailed: Bool?
  let maybeReply: ReplyPreview?
  let isPinned: Bool?
  let isSaved: Bool?
  /// Earlier versions, oldest first (empty if never edited).
  let edits: [MessageEdit]?
  /// Deleted for everyone: a placeholder instead of the body.
  let isDeleted: Bool?
  let maybeForwarded: ForwardedFrom?
  /// An own message the other member of a DM read: two ticks instead of one (#769).
  let isRead: Bool?
  /// An own message that reached a device of every other member: two grey ticks (#598).
  let isDelivered: Bool?
  /// A membership or channel change someone made, shown as a line instead of a bubble.
  let maybeWorkspaceEvent: WorkspaceEvent?
}

/// A membership or channel change and who made it (`WorkspaceEvent`, tagged by `event`). Read
/// leniently: a field missing or an event this version doesn't know never fails the extras.
enum WorkspaceEvent: Decodable, Equatable, Sendable {
  case memberAdded(user: String, by: String, sharesHistory: Bool)
  case memberRemoved(user: String, by: String)
  // Changes the server reports of the channel (issue #818): `maybeBy` names who made one only when
  // that member's own announcement matched it; `nil` words the line as the server's statement.
  case archived(maybeBy: String?)
  case unarchived(maybeBy: String?)
  case madePrivate(maybeBy: String?)
  case madePublic(maybeBy: String?)
  /// To the space named `space`; empty if this device doesn't know its name.
  case moved(maybeBy: String?, space: String)
  case pinned(by: String)
  /// A workspace admin joined the private channel (admin.md §2.4): by themselves, or let in by the
  /// channel owner `maybeApprovedBy` who answered their request.
  case adminJoined(user: String, maybeApprovedBy: String?)
  /// A workspace admin joined the private channel because `by` added them without an approval to
  /// ask for (admin.md §2.4.2).
  case adminAdded(user: String, by: String)
  /// `by` moved the conversation's call into the meeting room `room` (issue #1290). `roomName` is
  /// empty if the user isn't in the room: the line links to it only when it is set.
  case callMoved(by: String, room: String, roomName: String)
  case unknown

  private enum CodingKeys: String, CodingKey {
    case event, user, by, history, space, approvedBy, addedBy, room, roomName
  }

  init(from decoder: Decoder) throws {
    let container = try decoder.container(keyedBy: CodingKeys.self)
    let text = { (key: CodingKeys) -> String? in try? container.decodeIfPresent(String.self, forKey: key) }
    let by = text(.by) ?? ""
    let maybeBy = by.isEmpty ? nil : by
    switch text(.event) {
    case "member_added": self = .memberAdded(user: text(.user) ?? "", by: by, sharesHistory: text(.history) == "full")
    case "member_removed": self = .memberRemoved(user: text(.user) ?? "", by: by)
    case "archived": self = .archived(maybeBy: maybeBy)
    case "unarchived": self = .unarchived(maybeBy: maybeBy)
    case "made_private": self = .madePrivate(maybeBy: maybeBy)
    case "made_public": self = .madePublic(maybeBy: maybeBy)
    case "moved": self = .moved(maybeBy: maybeBy, space: text(.space) ?? "")
    case "pinned": self = .pinned(by: by)
    case "admin_joined":
      if let addedBy = text(.addedBy), !addedBy.isEmpty {
        self = .adminAdded(user: text(.user) ?? "", by: addedBy)
      } else {
        self = .adminJoined(user: text(.user) ?? "", maybeApprovedBy: text(.approvedBy).flatMap { $0.isEmpty ? nil : $0 })
      }
    case "call_moved": self = .callMoved(by: by, room: text(.room) ?? "", roomName: text(.roomName) ?? "")
    default: self = .unknown
    }
  }
}

